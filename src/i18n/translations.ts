export type TranslationKey = keyof typeof translations.en;

export function getTranslation(lang: SupportedLanguage, key: TranslationKey | string, fallback?: string): string {
  const langDict = (translations as any)[lang] || translations.en;
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  // Fallback to English
  if (translations.en && (translations.en as any)[key]) {
    return (translations.en as any)[key];
  }
  return fallback !== undefined ? fallback : String(key);
}
